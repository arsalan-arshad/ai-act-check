  const outer = document.getElementById('nest-host').attachShadow({ mode: 'open' });
  const inner = document.createElement('div');
  outer.appendChild(inner);
  inner.attachShadow({ mode: 'open' }).innerHTML = '<div class="copilot-frame">Nested shadow text</div>';
