describe('crawl: single page capture', () => {
  let server: TestServer;
  let crossOriginServer: TestServer;
  let result: CrawlResult;
  let outDir: string;
  let page: PageSnapshot;

  beforeAll(async () => {
    crossOriginServer = await startServer({ '/frame-cross': html('<p>Cross origin frame text</p>') });
    server = await startServer({
      '/': html(CHAT_PAGE.replace('@@CROSS@@', crossOriginServer.origin), { title: 'Home page', headers: { 'x-custom-header': 'Yes' } }),
      '/vendor/chat.js': { status: 200, headers: { 'content-type': 'text/javascript' }, body: 'window.__loaded = true;' },
      '/frame': html('<p>Hello from frame</p><button>Ask</button>'),
      '/img/ai.png': { status: 200, headers: { 'content-type': 'image/png' }, body: aiPng },
      '/img/clean.png': { status: 200, headers: { 'content-type': 'image/png' }, body: cleanPng },
      '/img/clean.jpg': { status: 200, headers: { 'content-type': 'image/jpeg' }, body: cleanJpeg },
      '/img/vector.svg': { status: 200, headers: { 'content-type': 'image/svg+xml' }, body: '<svg xmlns="http://www.w3.org/2000/svg" width="100" height="100"/>' },
      '/img/tracker.png': { status: 200, headers: { 'content-type': 'image/png' }, body: validPng(1, 1) },
    });
    ({ result, outDir } = await fastCrawl(`${server.origin}/`, { maxPages: 1 }));
    page = result.pages[0] as PageSnapshot;
  });
  afterAll(async () => {
    await Promise.all([server.close(), crossOriginServer.close()]);
    await cleanupTempDirs();
  });

  it('loads the page and fills the basic fields', () => {
    expect(result.startBlocked).toBeNull();
    expect(result.pages).toHaveLength(1);
    expect(page.url).toBe(`${server.origin}/`);
    expect(page.finalUrl).toBe(`${server.origin}/`);
    expect(page.status).toBe(200);
    expect(page.title).toBe('Home page');
    expect(page.lang).toBe('en');
    expect(new Date(page.fetchedAt).toISOString()).toBe(page.fetchedAt);
    expect(page.headers['content-type']).toContain('text/html');
    expect(page.headers['x-custom-header']).toBe('Yes');
    expect(Object.keys(page.headers).every((k) => k === k.toLowerCase())).toBe(true);
  });

  it('records timestamps, user agent and robots info on the result', () => {
    expect(result.userAgent).toMatch(/^ai-act-check\/\d+\.\d+\.\d+ \(open-source technical scanner; not legal advice\)$/);
    expect(new Date(result.startedAt).getTime()).toBeLessThanOrEqual(new Date(result.finishedAt).getTime());
    expect(result.startUrl).toBe(`${server.origin}/`);
    expect(result.robots).toEqual({ url: `${server.origin}/robots.txt`, fetched: false, status: 404, crawlDelaySeconds: null });
  });

  it('sends the honest User-Agent to the site', () => {
    const navigation = server.requests.find((r) => r.url === '/');
    expect(navigation?.headers['user-agent']).toBe(result.userAgent);
  });

  it('captures rendered html and text, including open shadow roots but not closed ones', () => {
    expect(page.html).toContain('<h1>Welcome home</h1>');
    expect(page.text).toContain('Welcome home');
    expect(page.text).toContain('Shadow hello');
    expect(page.text).toContain('Nested shadow text');
    expect(page.text).not.toContain('Closed shadow secret');
    expect(page.text).not.toContain('window.__vendorChat');
  });

  it('captures external and inline scripts and skips JSON data blocks', () => {
    const external = page.scripts.filter((s) => s.src !== null).map((s) => s.src);
    expect(external).toContain(`${server.origin}/vendor/chat.js`);
    const inline = page.scripts.filter((s) => s.src === null);
    expect(inline.some((s) => s.inlineSnippet?.includes('window.__vendorChat'))).toBe(true);
    expect(page.scripts.some((s) => s.inlineSnippet?.includes('"@type"'))).toBe(false);
  });

  it('captures absolute http(s) links with text, preferring aria-label, deduplicated', () => {
    expect(page.links).toContainEqual({ href: `${server.origin}/about#team`, text: 'About us (aria)' });
    expect(page.links.filter((l) => l.href === `${server.origin}/privacy`)).toHaveLength(1);
    expect(page.links.some((l) => l.href.startsWith('mailto:') || l.href.startsWith('javascript:'))).toBe(false);
  });

  it('captures dom candidates with how they matched and whether they are visible', () => {
    const byId = page.domCandidates.find((c) => c.id === 'chat-widget');
    expect(byId).toMatchObject({ tag: 'div', matchedBy: 'id', visible: true, inShadowRoot: false, className: 'launcher' });
    expect(byId?.text).toBe('Chat with our AI assistant');

    expect(page.domCandidates.find((c) => c.className === 'livechat-box')).toMatchObject({ matchedBy: 'class', visible: false });
    expect(page.domCandidates.find((c) => c.text === 'Data attribute widget')).toMatchObject({ matchedBy: 'attr' });
    expect(page.domCandidates.find((c) => c.ariaLabel === 'Support widget')).toMatchObject({ tag: 'section', matchedBy: 'aria' });
    expect(page.domCandidates.find((c) => c.title === 'Your copilot')).toMatchObject({ matchedBy: 'title' });
  });

  it('traverses open shadow roots (including nested) and records inShadowRoot', () => {
    const shadow = page.domCandidates.find((c) => c.className === 'chatbot-panel');
    expect(shadow).toMatchObject({ inShadowRoot: true, text: 'Shadow hello', matchedBy: 'class' });
    const nested = page.domCandidates.find((c) => c.className === 'copilot-frame');
    expect(nested).toMatchObject({ inShadowRoot: true, text: 'Nested shadow text' });
  });

  it('does not see into closed shadow roots', () => {
    expect(page.domCandidates.some((c) => c.className === 'chat-closed')).toBe(false);
  });

  it('dedupes identical candidates and skips class-only descendants of a candidate', () => {
    expect(page.domCandidates.filter((c) => c.className === 'chat-widget')).toHaveLength(1);
    expect(page.domCandidates.some((c) => c.className === 'chat-header')).toBe(false);
    expect(page.domCandidates.some((c) => c.id === 'chat-input')).toBe(true); // has its own id, so it stays
    expect(page.domCandidates.some((c) => c.id === 'chat-root')).toBe(true);
  });

  it('includes accessible iframe text, including cross-origin frames', () => {
    const same = page.iframes.find((f) => f.id === 'same');
    expect(same).toMatchObject({ src: `${server.origin}/frame`, title: 'Same origin frame', className: 'chat-frame', visible: true, accessible: true });
    expect(same?.text).toContain('Hello from frame');

    const cross = page.iframes.find((f) => f.id === 'cross');
    expect(cross?.src).toBe(`${crossOriginServer.origin}/frame-cross`);
    expect(cross).toMatchObject({ accessible: true, visible: true });
    expect(cross?.text).toContain('Cross origin frame text');

    expect(page.iframes.find((f) => f.id === 'hidden')).toMatchObject({ visible: false, accessible: true });
    expect(page.iframes.find((f) => f.id === 'srcdoc')?.text).toContain('Srcdoc text');
  });

  it('captures images with alt, size and nearby text, and inspects their metadata', () => {
    const ai = page.images.find((i) => i.src.endsWith('/img/ai.png'));
    expect(ai).toMatchObject({ alt: 'A robot', width: 64, height: 64, nearbyText: 'Generated by AI', fetchStatus: 'ok', contentType: 'image/png' });
    expect(ai?.markers).toMatchObject({ c2pa: true, aiToolHints: ['Midjourney'] });

    const clean = page.images.find((i) => i.src.endsWith('/img/clean.png'));
    expect(clean?.markers).toEqual({ c2pa: false, iptcDigitalSourceType: null, aiToolHints: [], exifSoftware: null });

    const inParagraph = page.images.find((i) => i.src.endsWith('/img/clean.jpg'));
    expect(inParagraph?.nearbyText).toContain('Photo credit');
  });

  it('skips svg, tiny, data: and unreadable images without storing bytes', () => {
    expect(page.images.find((i) => i.src.endsWith('/img/vector.svg'))).toMatchObject({ fetchStatus: 'skipped', markers: null });
    expect(page.images.find((i) => i.src.endsWith('/img/tracker.png'))).toMatchObject({ fetchStatus: 'skipped', markers: null });
    expect(page.images.some((i) => i.src.startsWith('data:'))).toBe(false);
    expect(JSON.stringify(page)).not.toMatch(/IDAT/);
  });

  it('writes a viewport screenshot and stores its relative path', async () => {
    expect(page.screenshot).toBe('screenshots/page-1.png');
    const file = await readFile(join(outDir, page.screenshot as string));
    expect(file.subarray(0, 8)).toEqual(Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]));
    const width = file.readUInt32BE(16);
    const height = file.readUInt32BE(20);
    expect(width).toBe(1366);
    expect(height).toBe(900);
  });

  it('records failed subresources without query strings or failing the page', () => {
    expect(page.loadErrors.some((e) => e.includes('unreachable.js'))).toBe(true);
    expect(page.loadErrors.join('\n')).not.toContain('SECRET');
  });

  it('never clicks or submits anything and survives alert/confirm dialogs', () => {
    const paths = server.requests.map((r) => r.url.split('?')[0]);
    expect(paths).not.toContain('/submit');
    expect(paths).not.toContain('/clicked');
    expect(server.requests.every((r) => r.method === 'GET')).toBe(true);
  });

  it('fetches images with a Range header', () => {
    const request = server.requests.find((r) => r.url === '/img/ai.png' && r.headers.range !== undefined);
    expect(request?.headers.range).toBe('bytes=0-262143');
  });
});

describe('crawl: capture limits and variants', () => {
  let server: TestServer;
  beforeAll(async () => {
    const manyCandidates = Array.from({ length: 100 }, (_, i) => `<div class="chat-${i}">c${i}</div>`).join('');
    const huge = `<p>${'x'.repeat(1_300_000)}</p>`;
    server = await startServer({
      '/many': html(manyCandidates),
      '/huge': html(huge),
      '/nolang': html('<p>No language</p>', { lang: null }),
      '/long-link': html(`<a href="/x">${'y'.repeat(500)}</a>`),
      '/many-imgs': html(Array.from({ length: 20 }, (_, i) => `<img src="/img/${i}.png" width="64" height="64">`).join('')),
      ...Object.fromEntries(Array.from({ length: 20 }, (_, i) => [`/img/${i}.png`, { status: 200, headers: { 'content-type': 'image/png' }, body: cleanPng }])),
    });
  });
  afterAll(async () => {
    await server.close();
    await cleanupTempDirs();
  });

  it('caps dom candidates at 40', async () => {
    const { result } = await fastCrawl(`${server.origin}/many`, { maxPages: 1 });
    expect(result.pages[0]?.domCandidates).toHaveLength(40);
  });

  it('truncates html and text', async () => {
    const { result } = await fastCrawl(`${server.origin}/huge`, { maxPages: 1 });
    const page = result.pages[0] as PageSnapshot;
    expect(page.html.length).toBe(1_000_000);
    expect(page.text.length).toBe(200_000);
  });

  it('reports a missing lang as null', async () => {
    const { result } = await fastCrawl(`${server.origin}/nolang`, { maxPages: 1 });
    expect(result.pages[0]?.lang).toBeNull();
  });

  it('limits link text to 200 characters', async () => {
    const { result } = await fastCrawl(`${server.origin}/long-link`, { maxPages: 1 });
    expect(result.pages[0]?.links[0]?.text).toHaveLength(200);
  });

  it('inspects at most maxImagesPerPage images', async () => {
    const { result } = await fastCrawl(`${server.origin}/many-imgs`, { maxPages: 1, maxImagesPerPage: 5 });
    const images = result.pages[0]?.images ?? [];
    expect(images).toHaveLength(20);
    expect(images.filter((i) => i.fetchStatus === 'ok')).toHaveLength(5);
    expect(images.filter((i) => i.fetchStatus === 'skipped')).toHaveLength(15);
  });
});
